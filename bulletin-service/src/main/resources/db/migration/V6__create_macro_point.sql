-- V6: macro observations from TCMB EVDS (E1-5, ADR 002). One row per series per observation date.

create table macro_point (
    id          bigint generated by default as identity primary key,
    series_code varchar(40)    not null,
    obs_date    date           not null,
    value       numeric(20, 6) not null,
    fetched_at  timestamptz    not null,
    constraint uk_macro_point_series_date unique (series_code, obs_date)
);

-- ingest_run now also records EVDS runs, whose targets are series rather than funds.
alter table ingest_run rename column fund_count to target_count;
alter table ingest_run rename column funds_failed to targets_failed;
