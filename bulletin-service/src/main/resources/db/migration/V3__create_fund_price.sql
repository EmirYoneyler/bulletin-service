-- V3: daily fund prices (E1-2). One row per fund per trading day; re-fetches upsert in place.

create table fund_price (
    id             bigint generated by default as identity primary key,
    fund_id        bigint         not null references funds (id) on delete cascade,
    price_date     date           not null,
    price          numeric(20, 6) not null check (price > 0),
    total_value    numeric(24, 2),
    investor_count integer        check (investor_count >= 0),
    source         varchar(20)    not null,
    fetched_at     timestamptz    not null,
    constraint uk_fund_price_fund_date unique (fund_id, price_date)
);

-- The unique constraint already indexes (fund_id, price_date) for per-fund lookups;
-- this one serves "all funds on a given day" queries.
create index idx_fund_price_price_date on fund_price (price_date);
