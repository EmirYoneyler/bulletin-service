create table funds (
    id              bigint generated by default as identity,
    name            varchar(255) not null,
    category        varchar(255) check (category in ('EMEKLILIK', 'HISSE', 'TAHVIL', 'KARMA', 'PARA_PIYASASI')),
    risk_level      varchar(255) check (risk_level in ('DUSUK', 'ORTA', 'YUKSEK')),
    return_rate     float(53),
    fund_size       float(53),
    period          varchar(255) check (period in ('AYLIK', 'UC_AYLIK', 'ALTI_AYLIK', 'YILLIK')),
    is_future_trade boolean,
    expiry_date     date,
    contract_size   float(53),
    created_at      timestamp(6),
    primary key (id)
);
