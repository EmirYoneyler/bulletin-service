-- V5: one row per data ingestion run (E1-4), for the job summary and later GET /api/admin/ingest-runs (E8-2).

create table ingest_run (
    id             bigint generated by default as identity primary key,
    source         varchar(20) not null,
    trigger_type   varchar(20) not null,
    status         varchar(20) not null,
    range_from     date        not null,
    range_to       date        not null,
    started_at     timestamptz not null,
    finished_at    timestamptz,
    fund_count     integer     not null default 0,
    funds_failed   integer     not null default 0,
    rows_written   integer     not null default 0,
    rows_unchanged integer     not null default 0,
    errors         text
);

create index idx_ingest_run_started_at on ingest_run (started_at desc);
