package com.fonbulteni.bulletinservice.db;

import com.fonbulteni.bulletinservice.repository.FundRepository;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.testcontainers.service.connection.ServiceConnection;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * A database created earlier by ddl-auto=update (no Flyway history) must be baselined at V1,
 * keep its data and pass schema validation.
 */
@Tag("integration")
@SpringBootTest
@ActiveProfiles("test")
@Testcontainers(disabledWithoutDocker = true)
class FlywayExistingDatabaseTest {

    @ServiceConnection
    static PostgreSQLContainer<?> postgres = new PostgreSQLContainer<>("postgres:16-alpine");

    static {
        // Started and seeded before the Spring context (and therefore Flyway) comes up.
        postgres.start();
        seedLegacySchema();
    }

    @Autowired
    JdbcTemplate jdbc;

    @Autowired
    FundRepository fundRepository;

    private static void seedLegacySchema() {
        try (Connection connection = DriverManager.getConnection(
                postgres.getJdbcUrl(), postgres.getUsername(), postgres.getPassword());
             Statement statement = connection.createStatement()) {
            // Same shape Hibernate produced with ddl-auto=update before Flyway existed.
            statement.execute("""
                    create table funds (
                        contract_size float(53), expiry_date date, fund_size float(53),
                        is_future_trade boolean, return_rate float(53), created_at timestamp(6),
                        id bigint generated by default as identity,
                        category varchar(255) check (category in ('EMEKLILIK','HISSE','TAHVIL','KARMA','PARA_PIYASASI')),
                        name varchar(255) not null,
                        period varchar(255) check (period in ('AYLIK','UC_AYLIK','ALTI_AYLIK','YILLIK')),
                        risk_level varchar(255) check (risk_level in ('DUSUK','ORTA','YUKSEK')),
                        primary key (id))""");
            statement.execute("insert into funds (name, category) values ('Eski Kayıt', 'TAHVIL')");
        } catch (SQLException e) {
            throw new IllegalStateException("Could not seed legacy schema", e);
        }
    }

    @Test
    void baselinesExistingSchemaWithoutRunningV1() {
        Map<String, Object> baseline = jdbc.queryForMap(
                "select version, type, success from flyway_schema_history where version = '1'");

        assertThat(baseline.get("type")).isEqualTo("BASELINE");
        assertThat(baseline.get("success")).isEqualTo(true);
    }

    @Test
    void keepsExistingData() {
        assertThat(fundRepository.findAll())
                .singleElement()
                .satisfies(fund -> assertThat(fund.getName()).isEqualTo("Eski Kayıt"));
    }
}
